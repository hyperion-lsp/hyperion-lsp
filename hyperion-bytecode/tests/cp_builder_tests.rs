#[test]
fn test_builder_parser_roundtrip() {
    // This test verifies that indices produced by the builder can be correctly
    // interpreted by code that expects JVM-standard 1-based indexing

    let mut builder = ConstantPoolBuilder::new();

    // Build a constant pool with various types
    let string_idx = builder.add_utf8("TestString");
    let class_name_idx = builder.add_utf8("TestClass");
    let class_idx = builder.add_class("TestClass");
    let int_idx = builder.add_integer(100);

    // Verify indices are 1-based and sequential
    assert_eq!(string_idx, 1);
    // class_name_idx will be deduplicated from class_idx's UTF8
    assert_eq!(class_name_idx, 2);
    assert_eq!(class_idx, 3);
    assert_eq!(int_idx, 4);

    // Simulate parser behavior: access entries using 0-based array indexing
    // (index - 1) because arrays are 0-based but CP indices are 1-based
    let entries = builder.get_entries();

    // Access using (index - 1) as parser would
    match &entries[(string_idx - 1) as usize] {
        ConstantPoolItem::Utf8(s) => assert_eq!(s, "TestString"),
        _ => panic!("Wrong entry type"),
    }

    match &entries[(class_idx - 1) as usize] {
        ConstantPoolItem::Class { name_index } => {
            assert_eq!(*name_index, class_name_idx);
        }
        _ => panic!("Wrong entry type"),
    }

    match &entries[(int_idx - 1) as usize] {
        ConstantPoolItem::Integer(v) => assert_eq!(*v, 100),
        _ => panic!("Wrong entry type"),
    }
}

