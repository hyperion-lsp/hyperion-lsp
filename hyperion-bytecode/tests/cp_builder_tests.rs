#[test]
fn test_zero_index_is_unused() {
    // Index 0 should never be used or returned by the builder
    let mut builder = ConstantPoolBuilder::new();

    // Add multiple entries
    let indices = [
        builder.add_utf8("a"),
        builder.add_utf8("b"),
        builder.add_integer(1),
        builder.add_float(2.0),
        builder.add_class("C"),
    ];

    // None of the indices should be 0
    for (i, idx) in indices.iter().enumerate() {
        assert!(*idx > 0, "Index {} returned 0, which is reserved", i);
    }

    // The minimum index should be 1
    let min_idx = indices.iter().min().unwrap();
    assert_eq!(*min_idx, 1, "Minimum index should be 1");
}

#[test]
fn test_complex_constant_pool() {
    // Build a realistic constant pool with many entry types
    let mut builder = ConstantPoolBuilder::new();

    // Add various constants in a realistic order
    let object_class = builder.add_class("java/lang/Object");
    let test_class = builder.add_class("TestClass");
    let init_ref = builder.add_method_ref("java/lang/Object", "<init>", "()V");
    let field_ref = builder.add_field_ref("TestClass", "value", "I");

    let long_const = builder.add_long(9999999999);
    let string_const = builder.add_utf8("Hello");

    // Verify all indices are valid (> 0)
    let all_indices = vec![
        object_class,
        test_class,
        init_ref,
        field_ref,
        long_const,
        string_const,
    ];

    for idx in &all_indices {
        assert!(*idx > 0, "All indices should be > 0");
    }

    // Verify we can access all entries using (index - 1)
    let entries = builder.get_entries();
    for idx in &all_indices {
        let entry_idx = (*idx - 1) as usize;
        assert!(
            entry_idx < entries.len(),
            "Index {} (array position {}) out of bounds (len: {})",
            idx,
            entry_idx,
            entries.len()
        );
    }
}

#[test]
fn test_wide_entry_boundary() {
    // Test that wide entries are handled correctly when they appear
    // at various positions in the constant pool
    let mut builder = ConstantPoolBuilder::new();

    // Regular entry
    let idx1 = builder.add_utf8("before");
    assert_eq!(idx1, 1);

    // Wide entry (Long)
    let idx2 = builder.add_long(123);
    assert_eq!(idx2, 2);

    // Next entry should skip the placeholder slot
    let idx3 = builder.add_utf8("after_long");
    assert_eq!(idx3, 4);

    // Another wide entry (Double)
    let idx4 = builder.add_double(3.14);
    assert_eq!(idx4, 5);

    // Next entry skips placeholder
    let idx5 = builder.add_integer(999);
    assert_eq!(idx5, 7);

    let entries = builder.get_entries();

    // Total entries: 1 (UTF8) + 2 (Long) + 1 (UTF8) + 2 (Double) + 1 (Int) = 7
    assert_eq!(entries.len(), 7);
}
