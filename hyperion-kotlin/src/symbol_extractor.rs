    /// Extract declared parameter type+name strings from a function's
    /// `PARAMETER_LIST`.
    ///
    /// Produces entries in the "TypeName paramName" shape used by the Java
    /// extractor (`extract_method_parameters` in
    /// `hyperion_workspace::symbol_extractor`), so parameter descriptors are
    /// consistent across languages. Types are taken as written (no type
    /// inference); `vararg` parameters get a `vararg ` type prefix to keep
    /// the declared form faithful.
    fn extract_function_parameters(node: &SyntaxNode) -> Vec<String> {
        let Some(param_list) = node
            .children()
            .find(|c| c.kind() == SyntaxKind::PARAMETER_LIST)
        else {
            return Vec::new();
        };

        param_list
            .children()
            .filter(|c| c.kind() == SyntaxKind::PARAMETER)
            .map(|param| {
                let mut name: Option<String> = None;
                let mut param_type = String::new();
                let mut is_vararg = false;

                for token_or_node in param.children_with_tokens() {
                    match token_or_node {
                        NodeOrToken::Token(token) => match token.kind() {
                            SyntaxKind::VARARG_KW => is_vararg = true,
                            _ if Self::is_identifier_or_soft_keyword(token.kind())
                                && name.is_none() =>
                            {
                                name = Some(token.text().to_string());
                            }
                            _ => {}
                        },
                        NodeOrToken::Node(child_node) => {
                            if child_node.kind() == SyntaxKind::TYPE_REF {
                                if let Some(type_str) =
                                    Self::extract_type_from_type_ref(&child_node)
                                {
                                    param_type = type_str;
                                }
                            }
                        }
                    }
                }

                let name = name.unwrap_or_else(|| "arg".to_string());
                let param_type = if is_vararg {
                    format!("vararg {param_type}")
                } else {
                    param_type
                };

                if param_type.is_empty() {
                    name
                } else {
                    format!("{param_type} {name}")
                }
            })
            .collect()
    }

