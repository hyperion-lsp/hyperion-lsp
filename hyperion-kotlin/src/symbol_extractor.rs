    /// The expansion's type arguments are reported, qualified the
    /// way the expanded class is, and as written where this file's text
    /// cannot qualify them. A generic alias reports its type parameters in
    /// order, and its arguments keep their names as written, even a name an
    /// import also binds. An expansion written raw has none.
    #[test]
    fn typealias_expansion_type_arguments_are_reported() {
        let result = SymbolExtractor::extract_for_file(
            "package app\n\n\
             import model.User\n\
             import java.util.HashMap\n\n\
             typealias Names = java.util.ArrayList<String>\n\
             typealias Pairs = kotlin.collections.Map<String, Int>\n\
             typealias Users = java.util.ArrayList<User?>\n\
             typealias Index = HashMap<String, java.util.List<out User>>\n\
             typealias Wild = java.util.ArrayList<*>\n\
             typealias Box<T> = java.util.ArrayList<T>\n\
             typealias Nested<T> = HashMap<String, java.util.List<T>>\n\
             typealias Swap<User, B> = HashMap<B, out User?>\n\
             typealias Raw = java.util.ArrayList\n\
             typealias Text = java.lang.StringBuilder\n",
            Some("Aliases"),
        )
        .expect("valid Kotlin source");
        let aliases = result
            .type_aliases
            .iter()
            .map(|alias| {
                (
                    alias.fqn.as_str(),
                    alias.expanded_class.as_str(),
                    alias.type_parameters.clone(),
                    alias.expanded_type_arguments.clone(),
                )
            })
            .collect::<Vec<_>>();
        let strings = |arguments: &[&str]| {
            arguments
                .iter()
                .map(|argument| (*argument).to_owned())
                .collect::<Vec<_>>()
        };
        let none = Vec::new;
        assert_eq!(
            aliases,
            [
                (
                    "app.Names",
                    "java.util.ArrayList",
                    none(),
                    strings(&["String"])
                ),
                (
                    "app.Pairs",
                    "kotlin.collections.Map",
                    none(),
                    strings(&["String", "Int"])
                ),
                (
                    "app.Users",
                    "java.util.ArrayList",
                    none(),
                    strings(&["model.User?"])
                ),
                (
                    "app.Index",
                    "java.util.HashMap",
                    none(),
                    strings(&["String", "java.util.List<out model.User>"])
                ),
                ("app.Wild", "java.util.ArrayList", none(), strings(&["*"])),
                (
                    "app.Box",
                    "java.util.ArrayList",
                    strings(&["T"]),
                    strings(&["T"])
                ),
                (
                    "app.Nested",
                    "java.util.HashMap",
                    strings(&["T"]),
                    strings(&["String", "java.util.List<T>"])
                ),
                (
                    "app.Swap",
                    "java.util.HashMap",
                    strings(&["User", "B"]),
                    strings(&["B", "out User?"])
                ),
                ("app.Raw", "java.util.ArrayList", none(), none()),
                ("app.Text", "java.lang.StringBuilder", none(), none()),
            ]
        );
    }

    #[test]
    fn typealiases_this_file_cannot_qualify_are_not_reported() {
        let result = SymbolExtractor::extract_for_file(
            "package app\n\n\
             import java.util.Date\n\n\
             typealias Id<T> = T\n\
             typealias Shadowed<Date> = Date\n\
             private typealias Hidden = java.util.ArrayList<String>\n\
             typealias Callback = (Int) -> Unit\n\
             typealias Unqualified = ArrayList<String>\n\
             class Holder {\n    typealias Nested = java.util.ArrayList<String>\n}\n",
            Some("Aliases"),
        )
        .expect("Kotlin source");
        // `Shadowed`'s type parameter `Date` shadows the import. `Unqualified`
        // may bind to this package, a star import or a default import; only
        // the index can decide, so the extractor does not guess.
        assert!(result.type_aliases.is_empty(), "{:?}", result.type_aliases);
        assert_eq!(result.facade.as_deref(), Some("app.AliasesKt"));
    }
