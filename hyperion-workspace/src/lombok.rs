//! Lombok annotation processing and synthetic method generation
//!
//! This module handles detection of Lombok annotations and generates synthetic methods
//! that are added to the workspace index as if they were explicitly written in code.
//!
//! Supported annotations:
//! - @Getter / @Setter (field-level and class-level)
//! - @Data (implies @Getter, @Setter, @ToString, @EqualsAndHashCode, @RequiredArgsConstructor)
//! - @Value (immutable version of @Data)
//! - @Builder
//! - @AllArgsConstructor / @NoArgsConstructor / @RequiredArgsConstructor
//! - @Accessors (for method chaining)
//! - Logger annotations (@Slf4j, @Log4j2, @Log4j, @CommonsLog, @Log, @JBossLog,
//!   @Flogger, @XSlf4j): the synthetic `private static final <Logger> log` field

use crate::{Modifiers, Symbol, TextRange};
use hyperion_parser::syntax::{SyntaxKind, SyntaxNode};
use std::sync::Arc;

/// Represents a Lombok annotation found on a class or field
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LombokAnnotation {
    Getter,
    Setter,
    Data,
    Value,
    Builder,
    AllArgsConstructor,
    NoArgsConstructor,
    RequiredArgsConstructor,
    ToString,
    EqualsAndHashCode,
    Accessors {
        chain: bool,
        fluent: bool,
    },
    /// `@Slf4j` and friends: generates a `log` field of the given logger type.
    Logger {
        annotation: &'static str,
        logger_type: &'static str,
    },
}

/// A field extracted from a class for Lombok processing
#[derive(Debug, Clone)]
pub struct FieldInfo {
    pub name: String,
    pub type_name: String,
    pub is_final: bool,
    pub is_static: bool,
    pub annotations: Vec<LombokAnnotation>,
    pub range: TextRange,
}

/// Information about a class for Lombok processing
#[derive(Debug, Clone)]
pub struct ClassInfo {
    pub name: String,
    pub package: Option<String>,
    pub fields: Vec<FieldInfo>,
    pub annotations: Vec<LombokAnnotation>,
}

impl LombokAnnotation {
    /// Parse annotation from annotation node in AST
    pub fn from_annotation_node(node: &SyntaxNode) -> Option<Self> {
        // Extract annotation name from the node
        let name = extract_annotation_name(node)?;

        match name.as_str() {
            "Getter" | "lombok.Getter" => Some(LombokAnnotation::Getter),
            "Setter" | "lombok.Setter" => Some(LombokAnnotation::Setter),
            "Data" | "lombok.Data" => Some(LombokAnnotation::Data),
            "Value" | "lombok.Value" => Some(LombokAnnotation::Value),
            "Builder" | "lombok.Builder" => Some(LombokAnnotation::Builder),
            "AllArgsConstructor" | "lombok.AllArgsConstructor" => {
                Some(LombokAnnotation::AllArgsConstructor)
            }
            "NoArgsConstructor" | "lombok.NoArgsConstructor" => {
                Some(LombokAnnotation::NoArgsConstructor)
            }
            "RequiredArgsConstructor" | "lombok.RequiredArgsConstructor" => {
                Some(LombokAnnotation::RequiredArgsConstructor)
            }
            "ToString" | "lombok.ToString" => Some(LombokAnnotation::ToString),
            "EqualsAndHashCode" | "lombok.EqualsAndHashCode" => {
                Some(LombokAnnotation::EqualsAndHashCode)
            }
            "Accessors" | "lombok.experimental.Accessors" => {
                // Check for chain = true parameter
                let chain = has_annotation_param(node, "chain", "true");
                let fluent = has_annotation_param(node, "fluent", "true");
                Some(LombokAnnotation::Accessors { chain, fluent })
            }
            other => logger_for_annotation(other).map(|(annotation, logger_type)| {
                LombokAnnotation::Logger {
                    annotation,
                    logger_type,
                }
            }),
        }
    }
}

/// Simple annotation name and fully qualified logger type generated by
/// Lombok's logging annotations.
///
/// `@CustomLog` is deliberately absent: its type comes from `lombok.config`.
fn logger_for_annotation(name: &str) -> Option<(&'static str, &'static str)> {
    let simple = name.strip_prefix("lombok.").unwrap_or(name);
    let simple = simple
        .strip_prefix("extern.")
        .map_or(simple, |rest| rest.split_once('.').map_or(rest, |x| x.1));
    Some(match simple {
        "Slf4j" => ("Slf4j", "org.slf4j.Logger"),
        "XSlf4j" => ("XSlf4j", "org.slf4j.ext.XLogger"),
        "Log4j2" => ("Log4j2", "org.apache.logging.log4j.Logger"),
        "Log4j" => ("Log4j", "org.apache.log4j.Logger"),
        "CommonsLog" => ("CommonsLog", "org.apache.commons.logging.Log"),
        "Log" => ("Log", "java.util.logging.Logger"),
        "JBossLog" => ("JBossLog", "org.jboss.logging.Logger"),
        "Flogger" => ("Flogger", "com.google.common.flogger.FluentLogger"),
        _ => return None,
    })
}

/// Generate the `private static final` logger field Lombok adds to the class.
pub fn generate_logger_field(
    class_fqn: &str,
    annotation: &str,
    logger_type: &str,
    class_range: TextRange,
) -> Symbol {
    Symbol {
        fqn: format!("{class_fqn}.log").into(),
        simple_name: "log".into(),
        range: class_range,
        kind: crate::SymbolKind::FIELD,
        modifiers: Modifiers {
            is_private: true,
            is_static: true,
            is_final: true,
            ..Default::default()
        },
        container: Some(class_fqn.into()),
        return_type: Some(logger_type.into()),
        parent_class: None,
        interfaces: vec![],
        documentation: Some(
            format!("Logger instance generated by @{annotation} annotation").into(),
        ),
        parameters: vec![],
        type_parameters: Vec::new(),
        is_deprecated: false,
        receiver_type: None,
        kotlin: None,
        throws: None,
    }
}

/// Extract annotation name from annotation node
fn extract_annotation_name(node: &SyntaxNode) -> Option<String> {
    // Look for IDENT tokens in the annotation
    // For qualified names like @lombok.Data, we want "lombok.Data"
    // For simple names like @Data, we want "Data"
    // For parameterized annotations like @Accessors(chain=true), we only want "Accessors"
    let mut parts = Vec::new();

    for child in node.descendants_with_tokens() {
        if let Some(token) = child.as_token() {
            if token.kind().is_identifier() {
                parts.push(token.text().to_string());
                // Stop after finding identifiers that are part of the qualified name
                // Once we hit a '(', we've reached the parameters
            } else if token.kind() == SyntaxKind::L_PAREN {
                // Hit the parameter list, stop collecting identifiers
                break;
            }
        }
    }

    if !parts.is_empty() {
        Some(parts.join("."))
    } else {
        None
    }
}

/// Check if annotation has a specific parameter with a specific value
fn has_annotation_param(node: &SyntaxNode, param_name: &str, expected_value: &str) -> bool {
    // This is a simplified check - a full implementation would parse the annotation arguments
    let text = node.text().to_string();
    text.contains(&format!("{} = {}", param_name, expected_value))
        || text.contains(&format!("{}={}", param_name, expected_value))
}

/// Generate synthetic getter method for a field
pub fn generate_getter(field: &FieldInfo, class_fqn: &str, class_range: TextRange) -> Symbol {
    let method_name = getter_name(&field.name, &field.type_name);
    let method_fqn = format!("{}.{}()", class_fqn, method_name);

    Symbol {
        fqn: method_fqn.clone().into(),
        simple_name: method_name.into(),
        range: class_range, // Point to class since method doesn't exist in source
        kind: crate::SymbolKind::METHOD,
        modifiers: Modifiers {
            is_public: true,
            is_static: false,
            is_final: false,
            is_abstract: false,
            ..Default::default()
        },
        container: Some(class_fqn.into()),
        return_type: Some(field.type_name.clone().into()),
        parent_class: None,
        interfaces: vec![],
        documentation: None,
        parameters: vec![],
        type_parameters: Vec::new(),
        is_deprecated: false,
        receiver_type: None, // Java doesn't have extension functions
        kotlin: None,
        throws: None,
    }
}

/// Generate synthetic setter method for a field
pub fn generate_setter(
    field: &FieldInfo,
    class_fqn: &str,
    class_range: TextRange,
    chain: bool,
) -> Symbol {
    let method_name = setter_name(&field.name);
    let method_fqn = format!("{}.{}({})", class_fqn, method_name, field.type_name);

    // If @Accessors(chain = true), setter returns 'this' (the class type)
    // Must use fully qualified name for proper type resolution
    let return_type = if chain {
        Some(class_fqn.to_string())
    } else {
        None
    };

    Symbol {
        fqn: method_fqn.clone().into(),
        simple_name: method_name.into(),
        range: class_range,
        kind: crate::SymbolKind::METHOD,
        modifiers: Modifiers {
            is_public: true,
            is_static: false,
            is_final: false,
            is_abstract: false,
            ..Default::default()
        },
        container: Some(class_fqn.to_string().into()),
        return_type: return_type.map(Arc::from),
        parent_class: None,
        interfaces: vec![],
        documentation: None,
        parameters: vec![format!("{} {}", field.type_name, field.name).into()],
        type_parameters: Vec::new(),
        is_deprecated: false,
        receiver_type: None, // Java doesn't have extension functions
        kotlin: None,
        throws: None,
    }
}

/// Generate the synthetic Builder class
pub fn generate_builder_class(class_fqn: &str, class_range: TextRange) -> Symbol {
    let class_simple_name = class_fqn.split('.').next_back().unwrap_or("");
    // Builder is a nested class: com.example.User.UserBuilder
    let builder_class_fqn = format!("{}.{}Builder", class_fqn, class_simple_name);
    let builder_simple_name = format!("{}Builder", class_simple_name);

    Symbol {
        fqn: builder_class_fqn.into(),
        simple_name: builder_simple_name.into(),
        range: class_range,
        kind: crate::SymbolKind::CLASS,
        modifiers: Modifiers {
            is_public: true,
            is_static: true,
            is_final: false,
            is_abstract: false,
            ..Default::default()
        },
        container: Some(class_fqn.to_string().into()),
        return_type: None,
        parent_class: None,
        interfaces: vec![],
        documentation: None,
        parameters: vec![],
        type_parameters: Vec::new(),
        is_deprecated: false,
        receiver_type: None, // Java doesn't have extension functions
        kotlin: None,
        throws: None,
    }
}

/// Generate builder() static method
