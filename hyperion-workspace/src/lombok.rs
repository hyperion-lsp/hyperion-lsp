/// Generate getter method name following Java naming conventions
fn getter_name(field_name: &str, field_type: &str) -> String {
    // For boolean fields, use "is" prefix instead of "get"
    let prefix = if field_type == "boolean"
        || field_type == "Boolean"
        || field_type == "java.lang.Boolean"
    {
        "is"
    } else {
        "get"
    };

    // Capitalize first letter of field name
    let capitalized = capitalize_first(field_name);
    format!("{}{}", prefix, capitalized)
}

/// Generate setter method name
fn setter_name(field_name: &str) -> String {
    format!("set{}", capitalize_first(field_name))
}

/// Capitalize first character of a string
fn capitalize_first(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

/// Process Lombok annotations on a class and generate synthetic symbols
pub fn process_class_annotations(
    class_info: &ClassInfo,
    class_fqn: &str,
    class_range: TextRange,
) -> Vec<Symbol> {
    let mut synthetic_symbols = Vec::new();

    // Check for @Accessors to see if we should use chaining
    let has_chain = class_info
        .annotations
        .iter()
        .any(|a| matches!(a, LombokAnnotation::Accessors { chain: true, .. }));

    // Process class-level annotations
    for annotation in &class_info.annotations {
        match annotation {
            LombokAnnotation::Data | LombokAnnotation::Value => {
                // @Data and @Value generate getters for all fields
                for field in &class_info.fields {
                    if !field.is_static {
                        synthetic_symbols.push(generate_getter(field, class_fqn, class_range));

                        // @Data also generates setters (but @Value doesn't, as it's immutable)
                        if matches!(annotation, LombokAnnotation::Data) && !field.is_final {
                            synthetic_symbols.push(generate_setter(
                                field,
                                class_fqn,
                                class_range,
                                has_chain,
                            ));
                        }
                    }
                }
            }
            LombokAnnotation::Getter => {
                // Class-level @Getter generates getters for all non-static fields
                for field in &class_info.fields {
                    if !field.is_static && !field.annotations.contains(&LombokAnnotation::Getter) {
                        synthetic_symbols.push(generate_getter(field, class_fqn, class_range));
                    }
                }
            }
            LombokAnnotation::Setter => {
                // Class-level @Setter generates setters for all non-final, non-static fields
                for field in &class_info.fields {
                    if !field.is_static
                        && !field.is_final
                        && !field.annotations.contains(&LombokAnnotation::Setter)
                    {
                        synthetic_symbols.push(generate_setter(
                            field,
                            class_fqn,
                            class_range,
                            has_chain,
                        ));
                    }
                }
            }
            LombokAnnotation::Builder => {
                // Generate the Builder class itself
                synthetic_symbols.push(generate_builder_class(class_fqn, class_range));

                // Generate builder() static method
                synthetic_symbols.push(generate_builder_method(class_fqn, class_range));

                // Generate builder class with field setters and build()
                let class_simple_name = class_fqn.split('.').next_back().unwrap_or("");
                let builder_class_fqn = format!("{}.{}Builder", class_fqn, class_simple_name);

                for field in &class_info.fields {
                    if !field.is_static {
                        synthetic_symbols.push(generate_builder_field_setter(
                            field,
                            &builder_class_fqn,
                            class_range,
                        ));
                    }
                }

                synthetic_symbols.push(generate_build_method(
                    &builder_class_fqn,
                    class_fqn,
                    class_range,
                ));
            }
            LombokAnnotation::Logger {
                annotation,
                logger_type,
            } => {
                synthetic_symbols.push(generate_logger_field(
                    class_fqn,
                    annotation,
                    logger_type,
                    class_range,
                ));
            }
            _ => {
                // Other annotations like @ToString, @EqualsAndHashCode don't generate navigable methods
            }
        }
    }

    // Process field-level annotations
    for field in &class_info.fields {
        for annotation in &field.annotations {
            match annotation {
                LombokAnnotation::Getter => {
                    synthetic_symbols.push(generate_getter(field, class_fqn, class_range));
                }
                LombokAnnotation::Setter if !field.is_final => {
                    synthetic_symbols.push(generate_setter(
                        field,
                        class_fqn,
                        class_range,
                        has_chain,
                    ));
                }
                _ => {}
            }
        }
    }

    synthetic_symbols
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_getter_name_regular_field() {
        assert_eq!(getter_name("name", "String"), "getName");
        assert_eq!(getter_name("email", "String"), "getEmail");
    }

    #[test]
    fn test_getter_name_boolean_field() {
        assert_eq!(getter_name("active", "boolean"), "isActive");
        assert_eq!(getter_name("enabled", "Boolean"), "isEnabled");
        assert_eq!(getter_name("ready", "java.lang.Boolean"), "isReady");
    }

    #[test]
    fn test_setter_name() {
        assert_eq!(setter_name("name"), "setName");
        assert_eq!(setter_name("email"), "setEmail");
    }

    #[test]
    fn test_capitalize_first() {
        assert_eq!(capitalize_first("hello"), "Hello");
        assert_eq!(capitalize_first("world"), "World");
        assert_eq!(capitalize_first(""), "");
    }

    #[test]
    fn generated_methods_use_canonical_signatures_and_parameter_metadata() {
        let field = FieldInfo {
            name: "profile".to_string(),
            type_name: "com.model.Profile".to_string(),
            is_final: false,
            is_static: false,
            annotations: Vec::new(),
            range: TextRange::new(0, 1),
        };
        let range = TextRange::new(0, 10);

        let getter = generate_getter(&field, "com.example.Fixture", range);
        assert_eq!(getter.fqn.as_ref(), "com.example.Fixture.getProfile()");
        assert!(getter.parameters.is_empty());

        let setter = generate_setter(&field, "com.example.Fixture", range, true);
        assert_eq!(
            setter.fqn.as_ref(),
            "com.example.Fixture.setProfile(com.model.Profile)"
        );
        assert_eq!(
            setter.parameters.first().map(AsRef::as_ref),
            Some("com.model.Profile profile")
        );
        assert_eq!(setter.return_type.as_deref(), Some("com.example.Fixture"));

        let boolean_field = FieldInfo {
            name: "ssl".to_string(),
            type_name: "boolean".to_string(),
            is_final: false,
            is_static: false,
            annotations: Vec::new(),
            range: TextRange::new(0, 1),
        };
        let builder = generate_builder_class("com.example.Config", range);
        let builder_method = generate_builder_method("com.example.Config", range);
        let builder_setter =
            generate_builder_field_setter(&boolean_field, builder.fqn.as_ref(), range);
        let build_method = generate_build_method(builder.fqn.as_ref(), "com.example.Config", range);

        assert_eq!(builder.fqn.as_ref(), "com.example.Config.ConfigBuilder");
        assert_eq!(builder_method.fqn.as_ref(), "com.example.Config.builder()");
        assert_eq!(
            builder_method.return_type.as_deref(),
            Some("com.example.Config.ConfigBuilder")
        );
        assert_eq!(
            builder_setter.fqn.as_ref(),
            "com.example.Config.ConfigBuilder.ssl(boolean)"
        );
        assert_eq!(
            builder_setter.parameters.first().map(AsRef::as_ref),
            Some("boolean ssl")
        );
        assert_eq!(
            builder_setter.return_type.as_deref(),
            Some("com.example.Config.ConfigBuilder")
        );
        assert_eq!(
            build_method.fqn.as_ref(),
            "com.example.Config.ConfigBuilder.build()"
        );
        assert_eq!(
            build_method.return_type.as_deref(),
            Some("com.example.Config")
        );
    }
}
