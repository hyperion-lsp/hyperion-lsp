//! Code Generation Actions
//!
//! This module provides code generation functionality for the LSP:
//! - Constructor generation
//! - Getter/setter generation
//! - equals() and hashCode() generation
//! - toString() generation
//! - Interface method implementation
//! - Superclass method overriding

use hyperion_parser::syntax::{SyntaxKind, SyntaxNode};
use hyperion_semantics::db::{FileId, ParseDatabase};
use hyperion_workspace::WorkspaceIndex;
use std::collections::HashMap;
use std::sync::Arc;
use tower_lsp::lsp_types::{
    CodeAction, Position, Range, TextEdit as LspTextEdit, Url, WorkspaceEdit,
};
use tracing::debug;

use super::kinds;
use crate::inherited_members::{self, InheritedMethodStub};
use crate::position_utils::offset_to_position;
use crate::semantic_host::ReadTxn;

/// Provides code generation functionality
#[derive(Clone)]
pub struct GenerationActions<'txn> {
    txn: &'txn ReadTxn,
    workspace_index: Arc<WorkspaceIndex>,
}

impl<'txn> GenerationActions<'txn> {
    /// Creates a new GenerationActions instance
    pub const fn new(txn: &'txn ReadTxn, workspace_index: Arc<WorkspaceIndex>) -> Self {
        Self {
            txn,
            workspace_index,
        }
    }

    /// Parse `file_id` and describe the class the cursor is in.
    fn class_at(
        &self,
        file_id: FileId,
        source_text: &str,
        cursor: Position,
    ) -> Option<(SyntaxNode, ClassFacts)> {
        use crate::position_utils::position_to_offset;

        let root = {
            let snapshot = self.txn.snapshot();
            let parse_tree = snapshot.parse_file(file_id);
            parse_tree.syntax()
        };
        let offset = position_to_offset(source_text, cursor).ok()?;
        let token = root
            .token_at_offset(rowan::TextSize::from(offset as u32))
            .right_biased()?;
        let mut node = token.parent()?;
        while node.kind() != SyntaxKind::CLASS_DECL {
            node = node.parent()?;
        }
        let facts = ClassFacts::of(&node);
        Some((node, facts))
    }

    fn append_edit(
        node: &SyntaxNode,
        uri: &Url,
        source_text: &str,
        title: String,
        text: String,
    ) -> CodeAction {
        CodeAction {
            title,
            kind: Some(kinds::source_generate()),
            diagnostics: None,
            edit: Some(Self::append_to_type_body(node, uri, source_text, text)),
            command: None,
            is_preferred: None,
            disabled: None,
            data: None,
        }
    }

    /// Generate constructor with all instance fields (not offered where
    /// Lombok already generates an all-args constructor or one with the same
    /// parameters exists).
    pub fn generate_constructor_action(
        &self,
        file_id: FileId,
        uri: &Url,
        source_text: &str,
        cursor: Position,
    ) -> Option<CodeAction> {
        debug!("Checking for generate constructor action at {:?}", cursor);
        let (node, facts) = self.class_at(file_id, source_text, cursor)?;
        let fields = facts.instance_fields();
        if fields.is_empty() || facts.lombok.all_args_constructor() {
            return None;
        }
        if facts.constructor_param_counts.contains(&fields.len()) {
            return None;
        }
        let class_name = Self::extract_class_name(&node)?;
        let params: Vec<String> = fields
            .iter()
            .map(|field| format!("{} {}", field.typ, field.name))
            .collect();
        let assignments: Vec<String> = fields
            .iter()
            .map(|field| format!("        this.{0} = {0};", field.name))
            .collect();
        let constructor = format!(
            "\n    public {}({}) {{\n{}\n    }}\n",
            class_name,
            params.join(", "),
            assignments.join("\n")
        );
        Some(Self::append_edit(
            &node,
            uri,
            source_text,
            format!(
                "Generate constructor with {} field{}",
                fields.len(),
                if fields.len() == 1 { "" } else { "s" }
            ),
            constructor,
        ))
    }

    /// Generate the getters and setters that are still missing: not declared
    /// yet and not generated by Lombok (`@Data`, `@Getter`, `@Setter`, `@Value`).
    pub fn generate_getters_setters_action(
        &self,
        file_id: FileId,
        uri: &Url,
        source_text: &str,
        cursor: Position,
    ) -> Option<CodeAction> {
        debug!(
            "Checking for generate getters/setters action at {:?}",
            cursor
        );
        let (node, facts) = self.class_at(file_id, source_text, cursor)?;
        let mut methods = String::new();
        let mut touched = 0usize;
        for field in facts.instance_fields() {
            let capitalized = field
                .name
                .chars()
                .next()?
                .to_uppercase()
                .collect::<String>()
                + &field.name[1..];
            let getter_name = if field.typ == "boolean" {
                format!("is{capitalized}")
            } else {
                format!("get{capitalized}")
            };
            let setter_name = format!("set{capitalized}");
            let needs_getter = !facts.lombok.generates_getter(field)
                && !facts.method_names.contains(&getter_name)
                && !facts.method_names.contains(&format!("get{capitalized}"));
            if needs_getter {
                methods.push_str(&format!(
                    "\n    public {} {getter_name}() {{\n        return {};\n    }}\n",
                    field.typ, field.name
                ));
            }
            let needs_setter = !field.is_final
                && !facts.lombok.generates_setter(field)
                && !facts.method_names.contains(&setter_name);
            if needs_setter {
                methods.push_str(&format!(
                    "\n    public void {setter_name}({0} {1}) {{\n        this.{1} = {1};\n    }}\n",
                    field.typ, field.name
                ));
            }
            let missing = needs_getter || needs_setter;
            touched += usize::from(missing);
        }
        if touched == 0 {
            return None;
        }
        Some(Self::append_edit(
            &node,
            uri,
            source_text,
            format!(
                "Generate getters and setters for {touched} field{}",
                if touched == 1 { "" } else { "s" }
            ),
            methods,
        ))
    }

    /// Resolve the type declaration the cursor sits in, together with the
    /// inherited methods it may still redeclare.
    ///
    /// Both generation actions below used to answer this for themselves, and
    /// both answered it wrongly: the enclosing type was found by
    /// walking to the first `CLASS_DECL`, which is dead in an interface, enum
    /// or record, and the member set came from `get_class_members` keyed by the
    /// *written* supertype spelling, which is not an FQN and therefore matched
    /// nothing for any packaged or inherited supertype. Both questions now have
    /// one answer each, in `crate::inherited_members`.
    fn inherited_methods_at(
        &self,
        file_id: FileId,
        source_text: &str,
        cursor: Position,
    ) -> Option<(SyntaxNode, Vec<InheritedMethodStub>)> {
        use crate::position_utils::position_to_offset;

        let root = {
            let snapshot = self.txn.snapshot();
            snapshot.parse_file(file_id).syntax()
        };

        let offset = position_to_offset(source_text, cursor).ok()?;
        let token = root
            .token_at_offset(rowan::TextSize::from(offset as u32))
            .right_biased()?;
        let type_node = inherited_members::type_declaration_at(&token)?;
        let type_fqn = inherited_members::type_declaration_fqn(&type_node)?;
        let declared = inherited_members::method_names_declared_in(&type_node);
        let stubs =
            inherited_members::inherited_method_stubs(&self.workspace_index, &type_fqn, &declared);
        Some((type_node, stubs))
    }

    /// Build the workspace edit that appends `body` before the closing brace of
    /// `type_node`.
    fn append_to_type_body(
        type_node: &SyntaxNode,
        uri: &Url,
        source_text: &str,
        body: String,
    ) -> WorkspaceEdit {
        let type_end = type_node.text_range().end();
        let insert_pos =
            offset_to_position(source_text, (Into::<u32>::into(type_end) - 1) as usize);
        let mut changes = HashMap::new();
        changes.insert(
            uri.clone(),
            vec![LspTextEdit {
                range: Range {
                    start: insert_pos,
                    end: insert_pos,
                },
                new_text: body,
            }],
        );
        WorkspaceEdit {
            changes: Some(changes),
            document_changes: None,
            change_annotations: None,
        }
    }

    /// Implement the abstract methods the enclosing type still owes.
    ///
    /// "Abstract" is decided by the canonical effective-method election, not by
    /// which supertype was written: an interface `default` method is already
    /// implemented for every implementor, while a superinterface's abstract
    /// method is owed even though the class never names that interface.
    pub fn implement_interface_methods_action(
        &self,
        file_id: FileId,
        uri: &Url,
        source_text: &str,
        cursor: Position,
    ) -> Option<CodeAction> {
        debug!(
            "Checking for implement interface methods action at {:?}",
            cursor
        );

        let (type_node, stubs) = self.inherited_methods_at(file_id, source_text, cursor)?;
        let unimplemented = stubs
            .into_iter()
            .filter(|stub| stub.requires_implementation)
            .collect::<Vec<_>>();
        if unimplemented.is_empty() {
            debug!("No unimplemented inherited methods");
            return None;
        }

        let mut methods_code = String::new();
        for stub in &unimplemented {
            let body = if stub.return_type == "void" {
                "        throw new UnsupportedOperationException(\"Not implemented\");".to_string()
            } else {
                format!("        throw new UnsupportedOperationException(\"Not implemented\"); // TODO: return {}", stub.return_type)
            };
            methods_code.push_str(&format!(
                "\n    @Override\n    public {} {}({}) {{\n{body}\n    }}\n",
                stub.return_type,
                stub.name,
                stub.parameter_list()
            ));
        }

        Some(CodeAction {
            title: format!(
                "Implement {} interface method{}",
                unimplemented.len(),
                if unimplemented.len() == 1 { "" } else { "s" }
            ),
            kind: Some(kinds::source_generate_implement()),
            diagnostics: None,
            edit: Some(Self::append_to_type_body(
                &type_node,
                uri,
                source_text,
                methods_code,
            )),
            command: None,
            is_preferred: None,
            disabled: None,
            data: None,
        })
    }

    /// Override the concrete methods the enclosing type inherits.
    ///
    /// The candidate set is every inherited slot that already has a body,
    /// transitively through superclasses and superinterfaces (a `default`
    /// method is overridable exactly like a superclass method), minus the
    /// declarations Java forbids overriding at all.
    pub fn override_methods_action(
        &self,
        file_id: FileId,
        uri: &Url,
        source_text: &str,
        cursor: Position,
    ) -> Option<CodeAction> {
        debug!("Checking for override methods action at {:?}", cursor);

        let (type_node, stubs) = self.inherited_methods_at(file_id, source_text, cursor)?;
        let overridable = stubs
            .into_iter()
            .filter(|stub| !stub.requires_implementation)
            .collect::<Vec<_>>();
        if overridable.is_empty() {
            debug!("No overridable methods found");
            return None;
        }

        let mut methods_code = String::new();
        for stub in &overridable {
            let delegation = stub.super_call(&stub.argument_list());
            let super_call = if stub.return_type == "void" {
                format!("        {delegation};")
            } else {
                format!("        return {delegation};")
            };
            methods_code.push_str(&format!(
                "\n    @Override\n    public {} {}({}) {{\n{super_call}\n    }}\n",
                stub.return_type,
                stub.name,
                stub.parameter_list()
            ));
        }

        Some(CodeAction {
            title: format!(
                "Override {} method{}",
                overridable.len(),
                if overridable.len() == 1 { "" } else { "s" }
            ),
            kind: Some(kinds::source_generate_override()),
            diagnostics: None,
            edit: Some(Self::append_to_type_body(
                &type_node,
                uri,
                source_text,
                methods_code,
            )),
            command: None,
            is_preferred: None,
            disabled: None,
            data: None,
        })
    }

    /// Generate equals() and hashCode() methods based on fields
    pub fn generate_equals_hashcode_action(
        &self,
        file_id: FileId,
        uri: &Url,
        source_text: &str,
        cursor: Position,
    ) -> Option<CodeAction> {
        debug!(
            "Checking for generate equals/hashCode action at {:?}",
            cursor
        );
        let (node, facts) = self.class_at(file_id, source_text, cursor)?;
        let fields = facts
            .instance_fields()
            .into_iter()
            .filter(|field| !field.is_transient)
            .collect::<Vec<_>>();
        if fields.is_empty()
            || facts.lombok.generates_equals_hash_code()
            || facts.method_names.contains("equals")
            || facts.method_names.contains("hashCode")
        {
            return None;
        }
        let class_name = Self::extract_class_name(&node)?;
        let field_comparisons: Vec<String> = fields
            .iter()
            .map(|field| {
                let name = &field.name;
                if Self::is_primitive_type(&field.typ) {
                    format!("this.{name} == other.{name}")
                } else {
                    format!("java.util.Objects.equals(this.{name}, other.{name})")
                }
            })
            .collect();
        let equals_method = format!(
            r"
    @Override
    public boolean equals(Object obj) {{
        if (this == obj) return true;
        if (obj == null || getClass() != obj.getClass()) return false;
        {} other = ({}) obj;
        return {};
    }}
",
            class_name,
            class_name,
            field_comparisons.join("\n            && ")
        );
        let field_names: Vec<&str> = fields.iter().map(|field| field.name.as_str()).collect();
        let hashcode_method = format!(
            r"
    @Override
    public int hashCode() {{
        return java.util.Objects.hash({});
    }}
",
            field_names.join(", ")
        );
        Some(Self::append_edit(
            &node,
            uri,
            source_text,
            "Generate equals() and hashCode()".to_string(),
            format!("{equals_method}{hashcode_method}"),
        ))
    }

    /// Generate toString() method based on fields
    pub fn generate_tostring_action(
        &self,
        file_id: FileId,
        uri: &Url,
        source_text: &str,
        cursor: Position,
    ) -> Option<CodeAction> {
        debug!("Checking for generate toString action at {:?}", cursor);
        let (node, facts) = self.class_at(file_id, source_text, cursor)?;
        let fields = facts.instance_fields();
        if fields.is_empty()
            || facts.lombok.generates_to_string()
            || facts.method_names.contains("toString")
        {
            return None;
        }
        let class_name = Self::extract_class_name(&node)?;
        let field_strings: Vec<String> = fields
            .iter()
            .map(|field| format!("\"{0}=\" + {0}", field.name))
            .collect();
        let tostring_method = format!(
            r#"
    @Override
    public String toString() {{
        return "{} {{" +
            {} +
            "}}";
    }}
"#,
            class_name,
            field_strings.join(" + \", \" +\n            ")
        );
        Some(Self::append_edit(
            &node,
            uri,
            source_text,
            "Generate toString()".to_string(),
            tostring_method,
        ))
    }

    // ===== Helper Methods =====

    /// Extract field information from a field declaration node
    fn extract_field_info(field_node: &SyntaxNode) -> Option<(String, String)> {
        let mut field_type = None;
        let mut field_name = None;

        for child in field_node.children_with_tokens() {
            match child.kind() {
                SyntaxKind::PRIMITIVE_TYPE | SyntaxKind::CLASS_TYPE | SyntaxKind::ARRAY_TYPE => {
                    if let Some(node) = child.as_node() {
                        field_type = Some(node.text().to_string().trim().to_string());
                    }
                }
                SyntaxKind::IDENT => {
                    if let Some(token) = child.as_token() {
                        field_name = Some(token.text().to_string());
                    }
                }
                _ => {}
            }
        }

        Some((field_type?, field_name?))
    }

    /// Extract class name from class declaration node
    fn extract_class_name(class_node: &SyntaxNode) -> Option<String> {
        crate::navigation::import_resolver::extract_class_name(class_node)
    }

    /// Check if a type is a Java primitive
    fn is_primitive_type(typ: &str) -> bool {
        matches!(
            typ,
            "int" | "long" | "short" | "byte" | "char" | "boolean" | "float" | "double"
        )
    }
}

/// One instance field of the class being edited.
struct FieldFacts {
    typ: String,
    name: String,
    is_final: bool,
    is_transient: bool,
    annotations: Vec<String>,
}

/// Lombok annotations on a class: what it already generates.
#[derive(Default)]
struct LombokFlags {
    data: bool,
    value: bool,
    getter: bool,
    setter: bool,
    all_args: bool,
    builder: bool,
    to_string: bool,
    equals_hash_code: bool,
}

impl LombokFlags {
    const fn all_args_constructor(&self) -> bool {
        self.all_args || self.value
    }

    fn generates_getter(&self, field: &FieldFacts) -> bool {
        self.data || self.value || self.getter || field.annotations.iter().any(|a| a == "Getter")
    }

    fn generates_setter(&self, field: &FieldFacts) -> bool {
        // `@Value` makes every field final: no setters at all.
        !self.value && (self.data || self.setter || field.annotations.iter().any(|a| a == "Setter"))
    }

    const fn generates_equals_hash_code(&self) -> bool {
        self.data || self.value || self.equals_hash_code
    }

    const fn generates_to_string(&self) -> bool {
        self.data || self.value || self.to_string
    }
}

struct ClassFacts {
    fields: Vec<FieldFacts>,
    method_names: std::collections::HashSet<String>,
    constructor_param_counts: Vec<usize>,
    lombok: LombokFlags,
}

/// Annotation simple names and modifier kinds of the `MODIFIER_LIST` that
/// precedes a declaration (modifiers are siblings of their declaration).
fn preceding_modifier_facts(node: &SyntaxNode) -> (Vec<String>, Vec<SyntaxKind>) {
    let mut previous = node.prev_sibling_or_token();
    while let Some(element) = previous {
        match element.kind() {
            SyntaxKind::WHITESPACE
            | SyntaxKind::LINE_COMMENT
            | SyntaxKind::BLOCK_COMMENT
            | SyntaxKind::DOC_COMMENT => previous = element.prev_sibling_or_token(),
            SyntaxKind::MODIFIER_LIST => {
                let list = element.into_node().expect("modifier list is a node");
                let annotations = list
                    .children()
                    .filter(|child| child.kind() == SyntaxKind::ANNOTATION)
                    .map(|annotation| {
                        let text = annotation.text().to_string();
                        let name = text
                            .trim_start_matches('@')
                            .split('(')
                            .next()
                            .unwrap_or_default()
                            .trim();
                        name.rsplit('.').next().unwrap_or(name).to_string()
                    })
                    .collect();
                let kinds = list
                    .descendants_with_tokens()
                    .filter_map(rowan::NodeOrToken::into_token)
                    .map(|token| token.kind())
                    .collect();
                return (annotations, kinds);
            }
            _ => break,
        }
    }
    (Vec::new(), Vec::new())
}

impl ClassFacts {
    fn of(class: &SyntaxNode) -> Self {
        let (class_annotations, _) = preceding_modifier_facts(class);
        let has = |name: &str| class_annotations.iter().any(|a| a == name);
        let lombok = LombokFlags {
            data: has("Data"),
            value: has("Value"),
            getter: has("Getter"),
            setter: has("Setter"),
            all_args: has("AllArgsConstructor"),
            builder: has("Builder"),
            to_string: has("ToString"),
            equals_hash_code: has("EqualsAndHashCode"),
        };
        let mut fields = Vec::new();
        let mut method_names = std::collections::HashSet::new();
        let mut constructor_param_counts = Vec::new();
        for member in class.children() {
            match member.kind() {
                SyntaxKind::FIELD_DECL => {
                    let (annotations, kinds) = preceding_modifier_facts(&member);
                    if kinds.contains(&SyntaxKind::STATIC_KW) {
                        continue;
                    }
                    if let Some((typ, name)) = GenerationActions::extract_field_info(&member) {
                        fields.push(FieldFacts {
                            typ,
                            name,
                            // `@Value` makes every field final.
                            is_final: lombok.value || kinds.contains(&SyntaxKind::FINAL_KW),
                            is_transient: kinds.contains(&SyntaxKind::TRANSIENT_KW),
                            annotations,
                        });
                    }
                }
                SyntaxKind::METHOD_DECL => {
                    if let Some(name) = member
                        .children_with_tokens()
                        .filter_map(rowan::NodeOrToken::into_token)
                        .find(|token| token.kind().is_identifier())
                    {
                        method_names.insert(name.text().to_string());
                    }
                }
                SyntaxKind::CONSTRUCTOR_DECL => {
                    let count = member
                        .children()
                        .find(|child| child.kind() == SyntaxKind::PARAM_LIST)
                        .map_or(0, |params| {
                            params
                                .children()
                                .filter(|child| child.kind() == SyntaxKind::PARAM)
                                .count()
                        });
                    constructor_param_counts.push(count);
                }
                _ => {}
            }
        }
        let _ = lombok.builder;
        Self {
            fields,
            method_names,
            constructor_param_counts,
            lombok,
        }
    }

    fn instance_fields(&self) -> Vec<&FieldFacts> {
        self.fields.iter().collect()
    }
}
